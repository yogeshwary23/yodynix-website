// Writes web/sitemap.xml.
//
//   flutter test tool/sitemap/generate_sitemap.dart                                  homepage only
//   flutter test tool/sitemap/generate_sitemap.dart --dart-define=SITEMAP_SCOPE=all  every public page
//
// Run through `flutter test` because the route list comes from the app's
// content, which needs Flutter. Use `all` only once the site serves clean
// URLs (`/careers`, not `/#/careers`): until then those URLs open the
// homepage, so listing them would point Google at duplicates of it.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:yodynix_website/core/routing/app_routes.dart';

import 'sitemap_routes.dart';

const _scope = String.fromEnvironment('SITEMAP_SCOPE', defaultValue: 'home');

void main() {
  test('write web/sitemap.xml', () {
    final all = _scope == 'all';
    final routes = all ? publicRoutes() : [AppRoutes.home];
    final note = all
        ? '  Generated by tool/sitemap/generate_sitemap.dart; do not edit by hand.\n'
              '  Every public page, from the same content the router uses.'
        : '  Generated by tool/sitemap/generate_sitemap.dart; do not edit by hand.\n'
              '  Homepage only while the site uses hash URLs (/#/careers): other pages have\n'
              '  no URL of their own that Google can index yet. Regenerate with the full\n'
              '  route list once clean URLs are live (see the tool\'s header).';
    File('web/sitemap.xml').writeAsStringSync(sitemapXml(routes, lastModified: DateTime.now(), note: note));
    // ignore: avoid_print
    print('web/sitemap.xml: ${routes.length} URL(s)');
  });
}
